import csv,collections as C,sys
d=sys.argv[1]
p=list(csv.DictReader(open(d+'/p2.csv')))
print('rows',len(p),'success rate',sum(int(r['Class']) for r in p)/len(p))
print('sites',C.Counter(r['LaunchSite'] for r in p))
for k in ['LaunchSite','Orbit']:
  g=C.defaultdict(list)
  for r in p:g[r[k]].append(int(r['Class']))
  print(k,{a:(len(b),round(sum(b)/len(b),3)) for a,b in g.items()})
g=C.defaultdict(list)
for r in p:g[r['Date'][:4]].append(int(r['Class']))
print('year',{a:(len(b),round(sum(b)/len(b),2)) for a,b in sorted(g.items())})
s=list(csv.DictReader(open(d+'/sql.csv')))
print('sql rows',len(s),C.Counter(r['Launch_Site'] for r in s))
print('NASA CRS',sum(float(r['PAYLOAD_MASS__KG_']) for r in s if r['Customer']=='NASA (CRS)'))
v=[float(r['PAYLOAD_MASS__KG_']) for r in s if r['Booster_Version'].startswith('F9 v1.1')];print('v1.1 avg',sum(v)/len(v), 'exact', [float(r['PAYLOAD_MASS__KG_']) for r in s if r['Booster_Version'].strip()=='F9 v1.1'])
print('first ground',min(r['Date'] for r in s if r['Landing_Outcome']=='Success (ground pad)'))
print('drone 4-6k',[r['Booster_Version'] for r in s if r['Landing_Outcome']=='Success (drone ship)' and 4000<float(r['PAYLOAD_MASS__KG_'])<6000])
print('mission',C.Counter(r['Mission_Outcome'].strip() for r in s))
m=max(float(r['PAYLOAD_MASS__KG_']) for r in s);print('max',m,[r['Booster_Version'] for r in s if float(r['PAYLOAD_MASS__KG_'])==m])
print('2015 fail drone',[(r['Date'],r['Booster_Version'],r['Launch_Site']) for r in s if r['Date'][:4]=='2015' and r['Landing_Outcome']=='Failure (drone ship)'])
print('rank',C.Counter(r['Landing_Outcome'] for r in s if '2010-06-04'<=r['Date']<='2017-03-20').most_common())
print('CCA sites',[x for x in set(r['Launch_Site'] for r in s) if x.startswith('CCA')])
q=list(csv.DictReader(open(d+'/dash.csv')))
g=C.defaultdict(list)
for r in q:g[r['Launch Site']].append(int(r['class']))
tot=sum(sum(b) for b in g.values())
print('dash',len(q),{a:(len(b),sum(b),round(sum(b)/len(b),3),round(sum(b)/tot,3)) for a,b in g.items()})
g=C.defaultdict(list)
for r in q:g[r['Booster Version Category']].append(int(r['class']))
print('booster',{a:(len(b),round(sum(b)/len(b),2)) for a,b in g.items()})
for lo,hi in [(0,2000),(2000,4000),(4000,6000),(6000,10000)]:
  b=[int(r['class']) for r in q if lo<=float(r['Payload Mass (kg)'])<hi];print(lo,hi,len(b),round(sum(b)/max(len(b),1),2))
